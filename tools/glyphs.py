def xml(paths):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           '<!-- generated by tools/glyphs.py; edit there -->',
           '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
           '    android:width="48dp" android:height="48dp"',
           '    android:viewportWidth="48" android:viewportHeight="48">']
    for d, mode in paths:
        if mode in ("fill", "evenodd"):
            extra = ' android:fillType="evenOdd"' if mode == "evenodd" else ''
            out.append(f'    <path android:fillColor="#FFFFFF"{extra} android:pathData="{d}" />')
        else:
            _, w, cap, join = mode
            out.append(f'    <path android:strokeColor="#FFFFFF" android:strokeWidth="{w}" '
                       f'android:strokeLineCap="{cap}" android:strokeLineJoin="{join}" android:pathData="{d}" />')
    out.append('</vector>')
    return "\n".join(out) + "\n"

def svg_group(paths):
    s = []
    for d, mode in paths:
        if mode in ("fill", "evenodd"):
            s.append(f'<path fill="#fff" fill-rule="{"evenodd" if mode=="evenodd" else "nonzero"}" d="{d}"/>')
        else:
            _, w, cap, join = mode
            s.append(f'<path fill="none" stroke="#fff" stroke-width="{w}" stroke-linecap="{cap}" stroke-linejoin="{join}" d="{d}"/>')
    return "".join(s)

