        cols = ["#0050EF","#D80073","#A4C400","#FA6800","#00ABA9","#E51400","#6A00FF","#008A00","#F0A30A","#F472D0","#647687","#76608A"]
        n = len(G); per = 5; t = 120; g = 8
        rows = (n + per - 1) // per
        W = per * (t + g); H = rows * (t + g + 18)
        parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{H}"><rect width="100%" height="100%" fill="#000"/>']
        for i, (name, paths) in enumerate(G.items()):
            x = (i % per) * (t + g); y = (i // per) * (t + g + 18)
            parts.append(f'<rect x="{x}" y="{y}" width="{t}" height="{t}" fill="{cols[i % len(cols)]}"/>')
            # same proportion as on a small tile: glyph box ~ 0.63 of the tile
            sc = t * 0.63 / 48
            parts.append(f'<g transform="translate({x + (t - 48*sc)/2},{y + (t - 48*sc)/2}) scale({sc})">{svg_group(paths)}</g>')
            parts.append(f'<text x="{x+4}" y="{y+t+14}" fill="#fff" font-family="sans-serif" font-size="12">{name}</text>')
        parts.append("</svg>")
        svg = out + ".svg"
        open(svg, "w").write("".join(parts))
        subprocess.run(["rsvg-convert", "-o", out, svg], check=True)
        print("preview", out)
