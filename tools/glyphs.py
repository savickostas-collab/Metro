def gear(teeth=8, r_out=17.5, r_in=13.2, hole=6.2, cx=24, cy=24):
    """Gear with square-shouldered teeth and a round hole (even-odd fill)."""
    pts = []
    step = 2 * math.pi / teeth
    tw = step * 0.26  # half-width of a tooth top, in radians
    bw = step * 0.34  # half-width of a tooth base
    for i in range(teeth):
        a = i * step - math.pi / 2
        for ang, r in ((a - bw, r_in), (a - tw, r_out), (a + tw, r_out), (a + bw, r_in)):
            pts.append((cx + r * math.cos(ang), cy + r * math.sin(ang)))
    d = "M" + " L".join(f"{x:.2f} {y:.2f}" for x, y in pts) + " Z "
    d += f"M{cx + hole} {cy} A{hole} {hole} 0 1 0 {cx - hole} {cy} A{hole} {hole} 0 1 0 {cx + hole} {cy} Z"
    return (d, "evenodd")

